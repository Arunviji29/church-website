/*
# Church content tables: sermons, events, announcements, prayer_requests, gallery

1. New Tables
- `sermons` — sermon archive shown on the Sermons page: title, speaker, sermon_date, topic, scripture, description, youtube_id (for embedding), thumbnail_url.
- `events` — upcoming church events: title, description, event_date, time (free text like "11:00 AM – 3:00 PM"), location, image_url.
- `announcements` — short news items for the home page: title, body, pinned (shows first), created_at.
- `prayer_requests` — prayer requests submitted from the site: name, request, created_at. Readable only by signed-in staff.
- `gallery` — photo gallery entries: title, image_url, caption, sort_order.
  All tables use a uuid primary key generated by the database.

2. Security
- RLS enabled on every table.
- Public visitors (anon key) can READ sermons, events, announcements, and gallery — this content is intentionally public-facing (USING (true)).
- Only signed-in staff (authenticated) can INSERT, UPDATE, or DELETE sermons, events, announcements, and gallery.
- prayer_requests: anyone (anon or authenticated) can SUBMIT a request; only signed-in staff can read them.
- Explicit GRANTs matching exactly those verbs and roles, in the same migration.
- Indexes on sermon_date, event_date, and announcements.created_at for list ordering.

3. Seed Data
- The existing 9 sermons and 6 events from the site are inserted with FIXED uuid primary keys so a database rebuild always produces identical ids. ON CONFLICT DO NOTHING keeps re-runs safe.

4. Notes
- No destructive operations. Safe to re-apply.
*/

-- 1. Tables -----------------------------------------------------------

CREATE TABLE IF NOT EXISTS sermons (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  speaker text NOT NULL,
  sermon_date date NOT NULL DEFAULT CURRENT_DATE,
  topic text NOT NULL DEFAULT 'General',
  scripture text NOT NULL DEFAULT '',
  description text NOT NULL DEFAULT '',
  youtube_id text NOT NULL DEFAULT '',
  thumbnail_url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  event_date date NOT NULL,
  time text NOT NULL DEFAULT '',
  location text NOT NULL DEFAULT '',
  image_url text NOT NULL DEFAULT '',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS announcements (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  body text NOT NULL DEFAULT '',
  pinned boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS prayer_requests (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  name text NOT NULL DEFAULT 'Anonymous',
  request text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS gallery (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  title text NOT NULL,
  image_url text NOT NULL,
  caption text NOT NULL DEFAULT '',
  sort_order integer NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sermons_date ON sermons (sermon_date DESC);
CREATE INDEX IF NOT EXISTS idx_events_date ON events (event_date);
CREATE INDEX IF NOT EXISTS idx_announcements_created ON announcements (created_at DESC);

-- 2. RLS + grants + policies -------------------------------------------

ALTER TABLE sermons ENABLE ROW LEVEL SECURITY;
ALTER TABLE events ENABLE ROW LEVEL SECURITY;
ALTER TABLE announcements ENABLE ROW LEVEL SECURITY;
ALTER TABLE prayer_requests ENABLE ROW LEVEL SECURITY;
ALTER TABLE gallery ENABLE ROW LEVEL SECURITY;

GRANT SELECT ON sermons, events, announcements, gallery TO anon, authenticated;
GRANT INSERT, UPDATE, DELETE ON sermons, events, announcements, gallery TO authenticated;

GRANT INSERT ON prayer_requests TO anon, authenticated;
GRANT SELECT ON prayer_requests TO authenticated;

DROP POLICY IF EXISTS "sermons_public_read" ON sermons;
CREATE POLICY "sermons_public_read" ON sermons FOR SELECT
TO anon, authenticated USING (true);
DROP POLICY IF EXISTS "sermons_staff_insert" ON sermons;
CREATE POLICY "sermons_staff_insert" ON sermons FOR INSERT
TO authenticated WITH CHECK (auth.uid() IS NOT NULL);
DROP POLICY IF EXISTS "sermons_staff_update" ON sermons;
CREATE POLICY "sermons_staff_update" ON sermons FOR UPDATE
TO authenticated USING (auth.uid() IS NOT NULL) WITH CHECK (auth.uid() IS NOT NULL);
DROP POLICY IF EXISTS "sermons_staff_delete" ON sermons;
